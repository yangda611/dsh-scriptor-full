function outlineAt(plan: SeasonPlan, 集: number): EpisodeOutlineSlot {
  const slot = plan.集大纲[集 - 1]
  if (slot === undefined) throw new Error(`示例短剧没有第 ${集} 集的结构位`)
  return slot
}

